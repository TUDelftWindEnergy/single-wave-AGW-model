import numpy as np
import matplotlib.pyplot as plt
import os
from datetime import datetime

# --- User-defined parameters ---
Ny = 80          # Number of grid points in the y-direction
Nz = 80          # Number of grid points in the z-direction
delta_n = 5.0    # Grid resolution in meters (Δn)
# -------------------------------

# Create coordinate arrays for y and z
y = np.linspace(0, (Ny - 1) * delta_n, Ny)
z = np.linspace(0, (Nz - 1) * delta_n, Nz)

# Create 2D meshgrid
Y, Z = np.meshgrid(y, z, indexing='ij')  # Y[i,j], Z[i,j] at point (i,j)

# Print grid information
print("=== Grid Information ===")
print(f"Number of grid points in y-direction (Ny): {Ny}")
print(f"Number of grid points in z-direction (Nz): {Nz}")
print(f"Grid resolution (Δn): {delta_n} m")
print(f"Total domain size: {y[-1]:.1f} m (y) × {z[-1]:.1f} m (z)")
print(f"Grid shape (Y, Z): {Y.shape}")
print(f"Y-range: [{y[0]}, {y[-1]}] m")
print(f"Z-range: [{z[0]}, {z[-1]}] m")
print(f"Number of grid points: {Ny * Nz}")
print(f"Created on: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")

# Prepare flattened coordinate arrays for export (each row: y, z)
y_flat = Y.flatten()
z_flat = Z.flatten()
grid_points = np.column_stack((y_flat, z_flat))  # Shape: (Ny*Nz, 2)

# Create directory 'mesh' if it doesn't exist
mesh_dir = "mesh"
os.makedirs(mesh_dir, exist_ok=True)

# Generate base filename based on parameters
filename_base = f"grid_Ny{Ny}_Nz{Nz}_res{int(delta_n)}m"
data_filename_npz = os.path.join(mesh_dir, f"{filename_base}.npz")
data_filename_csv = os.path.join(mesh_dir, f"{filename_base}.csv")
data_filename_txt = os.path.join(mesh_dir, f"{filename_base}.txt")

# --- Save .npz (for Python) ---
np.savez(data_filename_npz,
         Y=Y, Z=Z,
         y_vector=y, z_vector=z,
         Ny=Ny, Nz=Nz, delta_n=delta_n)
print(f"\n[Saved] Binary grid data: {data_filename_npz}")

# --- Save .csv (for Excel, MATLAB, etc.) ---
header_csv = "y_coordinate (m), z_coordinate (m)"
np.savetxt(data_filename_csv, grid_points, delimiter=',', comments='', header=header_csv, fmt='%.6f')
print(f"[Saved] CSV grid data: {data_filename_csv}")

# --- Save .txt (space-delimited, simple format) ---
header_txt = "Grid data: y z coordinates in meters. Generated by Python."
np.savetxt(data_filename_txt, grid_points, delimiter=' ', comments='# ', header=header_txt, fmt='%.6f')
print(f"[Saved] TXT grid data: {data_filename_txt}")

# Verify all files exist
for f in [data_filename_npz, data_filename_csv, data_filename_txt]:
    if os.path.exists(f):
        size_kb = os.path.getsize(f) / 1024
        print(f"  ✓ {os.path.basename(f)} ({size_kb:.1f} KB)")
    else:
        print(f"  ✗ Failed to save: {f}")

# --- Visualization ---
plt.figure(figsize=(10, 8))
plt.scatter(Y, Z, s=8, c='blue', alpha=0.7, edgecolors='none')
plt.title(f'2D Grid: Ny={Ny}, Nz={Nz}, Δn={delta_n} m', fontsize=14)
plt.xlabel('Y (m)', fontsize=12)
plt.ylabel('Z (m)', fontsize=12)
plt.xlim(-delta_n, y[-1] + delta_n)
plt.ylim(-delta_n, z[-1] + delta_n)
plt.grid(True, alpha=0.3)
plt.axis('equal')
plt.tight_layout()

# Save plot in mesh folder
plot_filename = os.path.join(mesh_dir, f"{filename_base}.png")
plt.savefig(plot_filename, dpi=150, bbox_inches='tight')
print(f"[Saved] Visualization: {plot_filename}")
plt.show()

print("\n✅ Grid generation and export completed. Files are in './mesh/' directory.")